const fs = require('fs');
const path = require('path');
const {
  withAndroidManifest,
  withDangerousMod,
  withMainActivity,
} = require('@expo/config-plugins');

/**
 * AppsFlyer OneLink (contract nc1). Off unless NEARSY_APPSFLYER_ENABLED=true and
 * NEARSY_APPSFLYER_DEV_KEY is set (EAS variable, visibility Sensitive; never in
 * Git and never printed). A disabled build has no OneLink filter, no MainActivity
 * change and no dev key in its config.
 *
 * - App Link: https://nearsy.onelink.me/Uxo6, autoVerify. AppsFlyer hosts
 *   assetlinks.json for onelink.me with the SHA-256 fingerprints registered in
 *   the OneLink template. No URI-scheme fallback.
 * - MainActivity is singleTask and React Native does not call setIntent(). The
 *   AppsFlyer SDK reads the activity intent, so setIntent() is called only for a
 *   OneLink: OAuth returns (nearsy://...) never become the activity intent.
 */
const ONELINK_HOST = 'nearsy.onelink.me';
const ONELINK_PATH_PREFIX = '/Uxo6';
const DEV_KEY = /^[A-Za-z0-9]{10,64}$/;
const MARKER = '// @nearsy-appsflyer onNewIntent';

function resolveAppsFlyerExtras(env) {
  const requested =
    String(env.NEARSY_APPSFLYER_ENABLED || '')
      .trim()
      .toLowerCase() === 'true';
  if (!requested) return { enabled: false };
  const devKey = String(env.NEARSY_APPSFLYER_DEV_KEY || '').trim();
  if (DEV_KEY.test(devKey)) return { enabled: true, devKey };
  const message =
    '[appsflyer] NEARSY_APPSFLYER_ENABLED=true without a valid NEARSY_APPSFLYER_DEV_KEY. ' +
    'Create it as an EAS variable with visibility Sensitive. The value is never printed.';
  if (
    String(env.EAS_BUILD || '')
      .trim()
      .toLowerCase() === 'true'
  ) {
    throw new Error(message);
  }
  console.warn(message);
  return { enabled: false };
}

function oneLinkIntentFilters() {
  return [
    {
      action: 'VIEW',
      autoVerify: true,
      category: ['BROWSABLE', 'DEFAULT'],
      data: [{ scheme: 'https', host: ONELINK_HOST, pathPrefix: ONELINK_PATH_PREFIX }],
    },
  ];
}

const KOTLIN_ON_NEW_INTENT = `
  ${MARKER}
  override fun onNewIntent(intent: android.content.Intent) {
    val data = intent.data
    val path = data?.path ?: ""
    val isOneLink = data != null &&
      "https".equals(data.scheme, ignoreCase = true) &&
      "${ONELINK_HOST}".equals(data.host, ignoreCase = true) &&
      (path == "${ONELINK_PATH_PREFIX}" || path.startsWith("${ONELINK_PATH_PREFIX}/"))
    if (isOneLink) setIntent(intent)
    super.onNewIntent(intent)
  }
`;

/** Inserts the override before the last closing brace of MainActivity (Kotlin). */
function addOneLinkOnNewIntent(contents) {
  if (contents.includes(MARKER)) return contents;
  if (/override\s+fun\s+onNewIntent\s*\(/.test(contents)) {
    throw new Error('[appsflyer] MainActivity already overrides onNewIntent; merge by hand.');
  }
  const end = contents.lastIndexOf('}');
  if (end < 0) throw new Error('[appsflyer] MainActivity has no class body.');
  return `${contents.slice(0, end).replace(/\s*$/, '\n')}${KOTLIN_ON_NEW_INTENT}}\n`;
}

/**
 * Auto Backup: the SDK declares its own rules and expo-secure-store declares
 * others, so the manifest merge fails. Both are merged here: secure-store's
 * (only shared preferences, never SecureStore) plus AppsFlyer's exclusions, so
 * the SDK state is never restored onto another install.
 */
const BACKUP_RULES = 'nearsy_backup_rules';
const EXTRACTION_RULES = 'nearsy_data_extraction_rules';
const EXCLUDES = [
  ['sharedpref', 'SecureStore'],
  ['sharedpref', 'SecureStore.xml'],
  ['sharedpref', 'appsflyer-data'],
  ['sharedpref', 'appsflyer-data.xml'],
  ['sharedpref', 'appsflyer-purchase-data'],
  ['sharedpref', 'appsflyer-purchase-data.xml'],
];

function ruleLines(indent) {
  return [
    `${indent}<include domain="sharedpref" path="."/>`,
    ...EXCLUDES.map(([domain, path]) => `${indent}<exclude domain="${domain}" path="${path}"/>`),
  ].join('\n');
}

function backupRulesXml() {
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/appsflyerConfig.js: Android 11 and lower. -->
<full-backup-content>
${ruleLines('  ')}
</full-backup-content>
`;
}

function dataExtractionRulesXml() {
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/appsflyerConfig.js: Android 12 and higher. -->
<data-extraction-rules>
  <cloud-backup>
${ruleLines('    ')}
  </cloud-backup>
  <device-transfer>
${ruleLines('    ')}
  </device-transfer>
</data-extraction-rules>
`;
}

/** Not used: Samsung preinstall data. Removed like the advertising permissions. */
const REMOVED_PERMISSIONS = ['com.samsung.android.mapsagent.permission.READ_APP_INFO'];

function applyAppsFlyerManifest(manifest) {
  const root = manifest.manifest;
  root.$ = root.$ || {};
  root.$['xmlns:tools'] = 'http://schemas.android.com/tools';
  const permissions = (Array.isArray(root['uses-permission']) ? root['uses-permission'] : []).filter(
    (entry) => !REMOVED_PERMISSIONS.includes(entry?.$?.['android:name']),
  );
  root['uses-permission'] = [
    ...permissions,
    ...REMOVED_PERMISSIONS.map((name) => ({ $: { 'android:name': name, 'tools:node': 'remove' } })),
  ];
  const application = Array.isArray(root.application) ? root.application[0] : null;
  if (!application) throw new Error('[appsflyer] Manifest has no <application>.');
  application.$['android:fullBackupContent'] = `@xml/${BACKUP_RULES}`;
  application.$['android:dataExtractionRules'] = `@xml/${EXTRACTION_RULES}`;
  const replaced = new Set(
    String(application.$['tools:replace'] || '')
      .split(',')
      .map((value) => value.trim())
      .filter(Boolean),
  );
  replaced.add('android:fullBackupContent');
  replaced.add('android:dataExtractionRules');
  application.$['tools:replace'] = [...replaced].join(',');
  return manifest;
}

function withNearsyAppsFlyer(config, extras) {
  if (!extras.enabled) return config;
  let next = withMainActivity(config, (activity) => {
    if (activity.modResults.language !== 'kt') {
      throw new Error('[appsflyer] Expected a Kotlin MainActivity.');
    }
    activity.modResults.contents = addOneLinkOnNewIntent(activity.modResults.contents);
    return activity;
  });
  next = withAndroidManifest(next, (manifestConfig) => {
    manifestConfig.modResults = applyAppsFlyerManifest(manifestConfig.modResults);
    return manifestConfig;
  });
  return withDangerousMod(next, [
    'android',
    async (modConfig) => {
      const dir = path.join(modConfig.modRequest.platformProjectRoot, 'app/src/main/res/xml');
      fs.mkdirSync(dir, { recursive: true });
      fs.writeFileSync(path.join(dir, `${BACKUP_RULES}.xml`), backupRulesXml());
      fs.writeFileSync(path.join(dir, `${EXTRACTION_RULES}.xml`), dataExtractionRulesXml());
      return modConfig;
    },
  ]);
}

module.exports = {
  ONELINK_HOST,
  ONELINK_PATH_PREFIX,
  addOneLinkOnNewIntent,
  applyAppsFlyerManifest,
  backupRulesXml,
  dataExtractionRulesXml,
  oneLinkIntentFilters,
  resolveAppsFlyerExtras,
  withNearsyAppsFlyer,
};
